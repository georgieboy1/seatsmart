import {test,expect} from '@playwright/test';
test('four groups of four use blank walking aisles, not interior walls',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:/try it with a sample class/i}).click();
 await expect(page).toHaveURL(/\/charts\/new\/?\?layoutId=/);
 const chartUrl=page.url();
 await page.getByRole('link',{name:'Set teaching wall in Rooms'}).click();
 await page.getByRole('button',{name:'Groups',exact:true}).click();
 await page.getByLabel('Groups (1–12)',{exact:true}).fill('4');
 await page.getByLabel('Students per group (1–8)',{exact:true}).fill('4');
 page.once('dialog',async dialog=>{expect(dialog.message()).toContain('saved customizations');await dialog.accept();});
 await page.getByRole('button',{name:'Apply',exact:true}).click();
 await expect(page.getByRole('gridcell',{name:'Empty at row 3, column 3',exact:true})).toBeVisible();
 await expect(page.getByRole('gridcell',{name:'Wall at row 3, column 0',exact:true})).toBeVisible();
 await page.getByRole('gridcell',{name:'Wall at row 3, column 0',exact:true}).click();
 page.once('dialog',async dialog=>{await dialog.dismiss();});
 await page.getByRole('button',{name:'Apply',exact:true}).click();
 await expect(page.getByRole('gridcell',{name:'Door at row 3, column 0',exact:true})).toBeVisible();
 await page.getByLabel('Front wall on this map',{exact:true}).selectOption('top');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await page.reload();
 await expect(page.getByRole('gridcell',{name:'Empty at row 3, column 3',exact:true})).toBeVisible();
 await page.goto(chartUrl);
 await page.getByRole('button',{name:'Generate Seating Chart',exact:true}).click();
 const grid=page.getByRole('grid',{name:/Interactive seating chart grid/});
 await expect(grid.getByRole('gridcell',{name:/Walking space/})).toHaveCount(9);
 await expect(grid.getByText('P',{exact:true})).toHaveCount(22);
 const aisle=grid.getByRole('gridcell',{name:'Walking space at row 3, column 3',exact:true});
 expect(await aisle.evaluate(e=>getComputedStyle(e).borderTopWidth)).toBe('0px');
 await expect(page.getByText(/Placed:\s*16/)).toBeVisible();
 await page.emulateMedia({media:'print'});
 await expect(page.locator('#chart-print')).not.toContainText('empty');
 await page.emulateMedia({media:'screen'});
 await page.screenshot({path:'/tmp/syndesk-groups-corrected.png',fullPage:true});
});
